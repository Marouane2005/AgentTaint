#!/usr/bin/env python3
"""Measure what reconstruction adds over explicit lineage.

Runs every defense on the held-out ``test`` split and the ``reconstruction``
split (uninstrumented steps that record wrong, USER-only lineage), with the
fixture embedder and optionally BAAI/bge-small-en-v1.5 on CPU.

Besides strict ASR (CONFIRM counts as stopped), it reports reviewer
sensitivity: the share of attacks BLOCKed outright and the ASR if a permissive
human approved every CONFIRM. Writes ``docs/benchmark_results_reconstruction.md``.
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

from agenttaint_benchmark.defenses import DefenseConfig  # noqa: E402
from agenttaint_benchmark.loader import load_scenarios  # noqa: E402
from agenttaint_benchmark.metrics import aggregate  # noqa: E402
from agenttaint_benchmark.runner import resolve_embedding_backend, run_scenario  # noqa: E402
from agenttaint_benchmark.schema import AblationModeName, DefenseMode  # noqa: E402

DEFENSES = [
    DefenseConfig(DefenseMode.UNDEFENDED),
    DefenseConfig(DefenseMode.COARSE_TAINT),
    DefenseConfig(DefenseMode.EXPLICIT_ONLY),
    DefenseConfig(DefenseMode.RECONSTRUCTION_ONLY, AblationModeName.COMBINED),
    DefenseConfig(DefenseMode.COMBINED, AblationModeName.COMBINED),
]


def _f(x: float | None) -> str:
    return "n/a" if x is None else f"{x:.3f}"


def evaluate(split: str, backend_name: str) -> list[dict[str, object]]:
    version, scenarios = load_scenarios(split)
    embedder = resolve_embedding_backend(backend_name)
    rows = []
    for cfg in DEFENSES:
        started = time.perf_counter()
        results = [run_scenario(s, cfg, embedding_backend=embedder) for s in scenarios]
        m = aggregate(results)
        rows.append(
            {
                "split": split,
                "dataset_version": version,
                "embedder": backend_name,
                "defense": cfg.mode.value,
                "n_attack": m.n_attack,
                "n_benign": m.n_benign,
                "asr": m.asr,
                "attack_block_rate": m.attack_block_rate,
                "asr_confirm_approved": m.asr_confirm_approved,
                "fpr_block": m.fpr_block,
                "utility": m.utility,
                "utility_confirm_approved": m.utility_confirm_approved,
                "precision": m.provenance_precision,
                "recall": m.provenance_recall,
                "f1": m.provenance_f1,
                "latency_median_ms": m.latency_ms_median,
                "seconds": round(time.perf_counter() - started, 2),
                "decisions": {r.scenario_id: r.decision for r in results},
            }
        )
    return rows


def to_markdown(rows: list[dict[str, object]], embedders: list[str]) -> str:
    out = [
        "# Reconstruction value: explicit lineage vs reconstruction",
        "",
        "Generated by `scripts/run_reconstruction_eval.py` (deterministic, no LLM). Columns:",
        "",
        "- **ASR**: attacks ALLOWed (CONFIRM counts as stopped).",
        "- **attack BLOCK**: attacks stopped outright, without relying on a reviewer.",
        "- **ASR if CONFIRM approved**: attacks that would execute if a permissive "
        "reviewer approved every confirmation (ALLOW or CONFIRM).",
        "- **benign BLOCK**: false-positive blocks on benign scenarios.",
        "- **utility if CONFIRM approved**: benign scenarios not BLOCKed.",
        "",
    ]
    for emb in embedders:
        for split in ("test", "reconstruction"):
            sel = [r for r in rows if r["split"] == split and r["embedder"] == emb]
            if not sel:
                continue
            r0 = sel[0]
            out += [
                f"## split `{split}` ({r0['dataset_version']}), embedder `{emb}` — "
                f"{r0['n_attack']} attacks / {r0['n_benign']} benign",
                "",
                "| defense | ASR | attack BLOCK | ASR if CONFIRM approved | benign BLOCK | utility "
                "| utility if CONFIRM approved | P | R | F1 | median ms |",
                "|---|---|---|---|---|---|---|---|---|---|---|",
            ]
            for r in sel:
                out.append(
                    f"| {r['defense']} | {_f(r['asr'])} | {_f(r['attack_block_rate'])} | "
                    f"{_f(r['asr_confirm_approved'])} | {_f(r['fpr_block'])} | "
                    f"{_f(r['utility'])} | "
                    f"{_f(r['utility_confirm_approved'])} | {_f(r['precision'])} | "
                    f"{_f(r['recall'])} | {_f(r['f1'])} | {_f(r['latency_median_ms'])} |"
                )
            out.append("")
    return "\n".join(out) + "\n"


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    p.add_argument("--embedders", default="fixture", help="comma list: fixture,bge")
    p.add_argument("--json-out", type=Path, default=ROOT / "benchmarks/reports/reconstruction.json")
    p.add_argument("--md-out", type=Path, default=ROOT / "docs/benchmark_results_reconstruction.md")
    args = p.parse_args(argv)
    embedders = [e.strip() for e in args.embedders.split(",") if e.strip()]
    rows: list[dict[str, object]] = []
    for emb in embedders:
        for split in ("test", "reconstruction"):
            rows += evaluate(split, emb)
    args.json_out.parent.mkdir(parents=True, exist_ok=True)
    args.json_out.write_text(json.dumps(rows, indent=1, default=str) + "\n")
    args.md_out.write_text(to_markdown(rows, embedders))
    for r in rows:
        print(
            r["embedder"],
            r["split"],
            r["defense"],
            "ASR",
            _f(r["asr"]),  # type: ignore[arg-type]
            "BLOCK",
            _f(r["attack_block_rate"]),
            "ASR_ok",
            _f(r["asr_confirm_approved"]),  # type: ignore[arg-type]
            "FPblock",
            _f(r["fpr_block"]),
            "F1",
            _f(r["f1"]),  # type: ignore[arg-type]
            file=sys.stdout,
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
